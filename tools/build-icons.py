#!/usr/bin/env python3
"""
Regenerates admin/templates/aurox/aurox/icon.tpl from the icon
sets in aurox/js/aurox-admin.js and aurox/js/aurox-tools.js, so the menu
(rendered by Smarty) and the scripts always use the same icons.

Usage:  python3 tools/build-icons.py
Author: Chimnadindu Great Chibueze (https://github.com/GreatsLab)
"""
import pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
MOD = ROOT / "admin/templates/aurox"
icons = {}
for js in ("aurox/js/aurox-admin.js", "aurox/js/aurox-tools.js"):
    text = (MOD / js).read_text(encoding="utf-8")
    for name, svg in re.findall(r"^\s{4}([a-z]+):\s*'(<[^']+)'", text, re.M):
        icons.setdefault(name, svg)

lines = [
    "{* Aurox icon set - generated by tools/build-icons.py, do not edit by hand.",
    "   Usage: {include file=\"$template/aurox/icon.tpl\" i=\"users\"}  (optional: c=\"extra-class\")",
    "   Author: Chimnadindu Great Chibueze - https://github.com/GreatsLab *}",
    "<svg class=\"ax-svg{if !empty($c)} {$c}{/if}\" viewBox=\"0 0 24 24\" fill=\"none\" stroke=\"currentColor\" stroke-width=\"1.8\" stroke-linecap=\"round\" stroke-linejoin=\"round\" aria-hidden=\"true\" focusable=\"false\">",
]
first = True
for name, svg in icons.items():
    lines.append(("{if" if first else "{elseif") + f" $i eq '{name}'}}{svg}")
    first = False
lines.append("{else}" + icons["link"] + "{/if}</svg>")
out = MOD / "aurox/icon.tpl"
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {out.relative_to(ROOT)} with {len(icons)} icons")
